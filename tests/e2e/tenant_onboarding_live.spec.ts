import {navigateTo} from './navigation';
import {test,expect} from '@playwright/test';
import fs from 'node:fs';

// The isolated empty organization is created by prepare_e2e.py. Never print its credentials.
const login=JSON.parse(fs.readFileSync('.cache/e2e-login.json','utf8')).onboarding;
const directory='.cache/e2e-live';
fs.mkdirSync(directory,{recursive:true});

test('real empty workspace imports its first branch and refreshes session access',async({page})=>{
 expect(Boolean(login?.email&&login?.password&&login?.organization_id)).toBe(true);
 const scopedReads:string[]=[];
 page.on('request',request=>{
  const url=new URL(request.url());
  if(url.pathname.startsWith('/api/v1/')&&url.searchParams.has('branch_id'))scopedReads.push(url.pathname);
 });
 await page.goto('/');
 await page.getByLabel('Электрондық пошта',{exact:true}).fill(login.email);
 await page.getByLabel('Құпиясөз',{exact:true}).fill(login.password);
 await page.getByRole('button',{name:'Жүйеге кіру',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Алғашқы бөлімшені қосыңыз',exact:true})).toBeVisible();
 await expect(page.getByLabel('Бөлімше',{exact:true})).toHaveCount(0);await expect(page.locator('.cabinet-name')).toHaveText('Бөлімшелер жоқ');
 await expect(page.locator('.metric')).toHaveCount(0);
 expect(scopedReads).toEqual([]);
 const initial=await page.request.get('/api/v1/session/me');expect(initial.status()).toBe(200);
 const before=await initial.json();expect(before.user.branch_ids).toEqual([]);
 const settingsResponse=await page.request.get('/api/v1/settings');expect(settingsResponse.status()).toBe(200);
 const metadata=await settingsResponse.json();expect(metadata.organization.id).toBe(login.organization_id);
 expect(metadata.onboarding.branch_count).toBe(0);expect(metadata.organization.data_policy).toBe('synthetic_only');
 await page.getByRole('button',{name:'Бөлімшелер CSV файлын импорттау',exact:true}).click();
 await expect(page.getByLabel('Деректер',{exact:true})).toHaveValue('branches');
 const downloaded=page.waitForEvent('download');
 await page.locator('a[href="/api/v1/imports/template/branches"]').click();
 const download=await downloaded;await download.saveAs(directory+'/onboarding-branches-template.csv');
 const template=fs.readFileSync(directory+'/onboarding-branches-template.csv','utf8').replace(/^\ufeff/,'');
 const header=template.split(/\r?\n/)[0].split(',');expect(header).toEqual(['branch_id','branch_name','data_origin']);
 const row:Record<string,string>={branch_id:'001',branch_name:'Browser Synthetic Branch',data_origin:'SYNTHETIC'};
 const csv=header.join(',')+'\n'+header.map(field=>row[field]).join(',')+'\n';
 await page.getByLabel('CSV файлын таңдаңыз').setInputFiles({name:'branches.csv',mimeType:'text/csv',buffer:Buffer.from(csv)});
 await page.getByRole('button',{name:'Алдын ала қарау',exact:true}).click();
 await expect(page.getByRole('button',{name:'Импорттау',exact:true})).toBeEnabled();
 await page.getByRole('button',{name:'Импорттау',exact:true}).click();
 await expect(page.getByText('Деректер транзакциямен импортталды',{exact:true})).toBeVisible();
 await expect(page.locator('.cabinet-name')).toBeVisible();
 await expect(page.getByLabel('Бөлімше',{exact:true})).toHaveCount(0);
 await expect(page.locator('.cabinet-name')).toHaveText('Browser Synthetic Branch');
 const refreshed=await page.request.get('/api/v1/session/me');expect(refreshed.status()).toBe(200);
 const after=await refreshed.json();expect(after.user.id).toBe(before.user.id);expect(after.user.branch_ids).toEqual(['001']);
 const imported=await page.request.get('/api/v1/branches');expect(imported.status()).toBe(200);
 expect((await imported.json()).items.map((item:{branch_id:string})=>item.branch_id)).toEqual(['001']);
 await page.locator('.app-header').getByRole('button',{name:'Бүгін',exact:true}).click();
 await expect(page.locator('.next-action')).toContainText('Бұл бөлімшеде сатылым деректері әлі жоқ.');
 await expect(page.locator('.metric-value').nth(0)).toHaveText('—');
 await expect(page.locator('.metric-value').nth(1)).toHaveText('—');
 await expect(page.locator('.day-recap .empty')).toContainText('Бұл жерде әзірше дерек жоқ');
 await expect(page.locator('.day-attention')).not.toContainText('31.12.2025');
 await expect(page.locator('.day-recap')).not.toContainText('01.01.2026');
 await navigateTo(page,'sales');
 await expect(page.getByText('Таңдалған кезең: 04.12.2025 — 31.12.2025',{exact:true})).toBeVisible();
 await expect(page.getByText('Бұл жерде әзірше дерек жоқ',{exact:true})).toBeVisible();
 await expect(page.getByText('Соңғы сатылым: 31.12.2025',{exact:true})).toHaveCount(0);
 await page.locator('.app-header').getByRole('button',{name:'Баптаулар және басқару',exact:true}).click();
 await expect(page.locator('.settings-row').filter({has:page.getByRole('heading',{name:'Ұйым',exact:true})}).locator('span')).toHaveText(metadata.organization.name??'—');
 await expect(page.locator('.settings-row').filter({has:page.getByRole('heading',{name:'Уақыт белдеуі',exact:true})}).locator('span')).toHaveText(metadata.organization.timezone??'—');
 await expect(page.locator('.settings-row').filter({has:page.getByRole('heading',{name:'Бөлімше',exact:true})}).locator('span')).toHaveText('001');
 await navigateTo(page,'audit');
 await expect(page.locator('tbody')).toContainText('import.committed');
 await page.setViewportSize({width:390,height:844});
 await expect.poll(()=>page.locator('.sidebar').evaluate(element=>element.getBoundingClientRect().right)).toBeLessThanOrEqual(0.5);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.screenshot({path:directory+'/onboarding-audit-mobile.png',fullPage:true,animations:'disabled'});
});
